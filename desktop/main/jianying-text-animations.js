/** 按名称查动画（忽略空格，支持部分匹配）；找不到返回 null */
function findTextIntroAnimation(name) {
  if (!name) return null
  const key = String(name).trim().toLowerCase()
  return TEXT_INTRO_ANIMATIONS.find((a) => a.name.toLowerCase() === key)
    || TEXT_INTRO_ANIMATIONS.find((a) => a.name.toLowerCase().includes(key) || key.includes(a.name.toLowerCase()))
    || null
}

